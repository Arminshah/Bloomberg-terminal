function add(stories: Story[]) {
  if (!stories.length) return;
  news.set((s) => {
    const seen = new Set(s.stories.map((x) => x.id));
    const fresh = stories.filter((x) => !seen.has(x.id));
    if (!fresh.length) return s;
    const all = [...fresh, ...s.stories].sort((a, b) => b.time - a.time).slice(0, 600);
    return { stories: all, seq: s.seq + fresh.length };
  });
}

export function addRealStories(stories: Story[]) {
  add(stories);
}

/** Builds the story backlog for the last day and a half. */
export function seedNews() {
  const now = engine.now();
  const out: Story[] = [];
  const today = engine.today;
  const prev = prevBusinessDay(today);
  // Market wraps at the regional closes.
  out.push({ ...regionWrap('ASIA', dayStart(today) + 7 * 3600_000, true), time: Math.min(now - 60_000, dayStart(today) + 7 * 3600_000) });
  out.push({ ...regionWrap('EU', dayStart(prev) + 16 * 3600_000, true), time: dayStart(prev) + 15.75 * 3600_000 });
  out.push({ ...regionWrap('US', dayStart(prev) + 20 * 3600_000, true), time: dayStart(prev) + 20.1 * 3600_000 });
  // Economic releases.
  for (const e of ecoEvents(now - 2 * DAY_MS, now, now)) if (e.relevance >= 2 && e.actual != null) out.push(ecoStory(e));
  // Earnings and analyst actions within the last few days.
  for (const d of engine.securities) {
    if (d.cls !== 'equity') continue;
    for (const ev of earningsHistory(d)) if (ev.actual != null && ev.date > now - 4 * DAY_MS && ev.date <= now) out.push(earningsStory(d, ev));
    for (const v of analystViews(d).slice(0, 3)) if (v.date > now - 3 * DAY_MS && v.date <= now && v.action !== 'Maintain') out.push(analystStory(d, v));
  }
  // Movers today.
  const movers = engine.securities
    .filter((d) => d.cls === 'equity')
    .map((d) => ({ d, p: engine.quote(d.id)!.pct }))
    .sort((a, b) => Math.abs(b.p) - Math.abs(a.p))
    .slice(0, 6);
  const r = seeded(hashString(`news:${today}`));
  for (const m of movers) out.push(moverStory(m.d, m.p, now - Math.floor(r() * 5 * 3600_000), true));
  for (const id of ['CL1 Comdty', 'GC1 Comdty', 'XBTUSD Curncy', 'XETUSD Curncy', 'EURUSD Curncy', 'USDJPY Curncy', 'USGG10YR Index', 'HG1 Comdty', 'NG1 Comdty']) {
    const s = assetStory(id, now - Math.floor(r() * 6 * 3600_000));
    if (s) out.push(s);
  }
  out.push(previewStory(now - 3 * 3600_000));
  add(out.filter((s) => s.time <= now));
}

function previewStory(time: number): Story {
  const now = engine.now();
  const upcoming = engine.securities
    .filter((d) => d.cls === 'equity')
    .map((d) => {
      const ev = earningsHistory(d).find((e) => e.actual == null);
      return { d, ev };
    })
    .filter((x) => x.ev && x.ev.date >= now && x.ev.date < now + 8 * DAY_MS)
    .sort((a, b) => a.ev!.date - b.ev!.date);
  const eco = ecoEvents(now, now + 7 * DAY_MS, now).filter((e) => e.relevance >= 3).slice(0, 6);
  return {
    id: `preview:${engine.today}`,
    time,
    headline: `Week Ahead: ${upcoming.length ? `${upcoming.slice(0, 3).map((x) => shortName(x.d)).join(', ')} Report; ` : ''}${eco.length ? `${eco[0].country} ${eco[0].name} in Focus` : 'Quiet Data Calendar'}`,
    body: [
      upcoming.length
        ? `Companies scheduled to report in the coming days include ${upcoming.slice(0, 8).map((x) => `${shortName(x.d)} (${monthDay(x.ev!.date)})`).join(', ')}. See EVTS for the full calendar.`
        : 'No major companies in the Armin universe report in the coming week.',
      eco.length ? `Key economic releases: ${eco.map((e) => `${e.country} ${e.name} (${monthDay(e.time)})`).join('; ')}. See ECO for consensus estimates.` : '',
      SIM_NOTE,
    ].filter(Boolean),
    tickers: upcoming.slice(0, 8).map((x) => x.d.id),
    topics: ['TOP', 'EARN', 'ECO'],
    source: 'ARMN',
  };
}

const crossed = new Map<string, number>();
let lastWrap = 0;
let lastAsset = 0;
let lastEcoCheck = 0;

/** Live newsroom: call every few seconds. Returns flash-worthy stories. */
export function newsTick(): Story[] {
  const now = engine.now();
  const out: Story[] = [];
  // Threshold crossings on large moves.
  for (const d of engine.securities) {
    if (d.cls !== 'equity' && d.cls !== 'index') continue;
    const q = engine.quote(d.id);
    if (!q) continue;
    const step = d.cls === 'index' ? (d.ticker === 'VIX' ? 5 : 1) : 2.5;
    const bucket = Math.trunc(q.pct / step);
    const key = `${engine.today}:${d.id}`;
    const prevB = crossed.get(key);
    crossed.set(key, bucket);
    if (prevB === undefined || bucket === prevB || bucket === 0 || Math.abs(bucket) < Math.abs(prevB)) continue;
    if (d.cls === 'equity') out.push({ ...moverStory(d, q.pct, now, true), hot: true, headline: `*${shortName(d).toUpperCase()} ${q.pct > 0 ? 'EXTENDS GAIN TO' : 'EXTENDS DROP TO'} ${fmtNum(Math.abs(q.pct), 1)}%` });
    else {
      const name = shortName(d);
      out.push({
        id: `idx:${d.id}:${bucket}:${engine.today}`,
        time: now,
        headline: `*${name.toUpperCase()} ${q.pct > 0 ? 'RISES' : 'FALLS'} ${fmtNum(Math.abs(q.pct), 1)}% TO ${fmtNum(q.last, 2)}`,
        body: [`The ${name} was ${q.pct >= 0 ? 'up' : 'down'} ${fmtNum(Math.abs(q.pct), 2)}% at ${fmtNum(q.last, 2)}, having traded between ${fmtNum(q.low, 2)} and ${fmtNum(q.high, 2)}.`, SIM_NOTE],
        tickers: [d.id],
        topics: ['TOP', 'STK'],
        source: 'FIRST WORD',
        hot: true,
      });
    }
  }
  // Economic releases as their time passes.
  if (lastEcoCheck) for (const e of ecoEvents(lastEcoCheck, now, now)) if (e.actual != null && e.time > lastEcoCheck && e.relevance >= 2) out.push(ecoStory(e));
  lastEcoCheck = now;
  // Periodic regional wraps and asset stories.
  if (now - lastWrap > 20 * 60_000) {
    const hour = new Date(now).getUTCHours();
    const region = hour >= 13 && hour < 21 ? 'US' : hour >= 7 && hour < 16 ? 'EU' : 'ASIA';
    if (lastWrap) out.push(regionWrap(region, now, false));
    lastWrap = now;
  }
  if (now - lastAsset > 7 * 60_000) {
    if (lastAsset) {
      const pool = ['CL1 Comdty', 'CO1 Comdty', 'GC1 Comdty', 'SI1 Comdty', 'HG1 Comdty', 'NG1 Comdty', 'XBTUSD Curncy', 'XETUSD Curncy', 'SOLUSD Curncy', 'EURUSD Curncy', 'USDJPY Curncy', 'GBPUSD Curncy', 'USGG10YR Index', 'USGG2YR Index', 'GDBR10 Index', 'GJGB10 Index'];
      const ranked = pool.map((id) => ({ id, s: Math.abs(engine.quote(id)!.pct) / (engine.get(id)!.vol || 1) })).sort((a, b) => b.s - a.s);
      const s = assetStory(pick(Math.random, ranked.slice(0, 4)).id, now);
      if (s) out.push(s);
    }
    lastAsset = now;
  }
  add(out);
  return out.filter((s) => s.hot);
}

export function storyMatches(s: Story, topic: string | undefined, ticker: string | undefined, query: string | undefined): boolean {
  if (topic && topic !== 'ALL' && !s.topics.includes(topic)) return false;
  if (ticker && !s.tickers.includes(ticker)) return false;
  if (query) {
    const q = query.toUpperCase();
    const hay = `${s.headline} ${s.body.join(' ')} ${s.tickers.join(' ')} ${s.topics.join(' ')}`.toUpperCase();
    if (!q.split(/\s+/).every((w) => hay.includes(w))) return false;
  }
  return true;
}
