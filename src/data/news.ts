const fmtPx = (def: SecurityDef, v: number) => {
  const s = fmtNum(v, def.dec);
  if (def.ccy === 'USD' && def.cls === 'equity') return `$${s}`;
  if (def.ccy === 'GBp') return `${s} pence`;
  if (def.ccy === 'EUR') return `€${s}`;
  return `${s} ${def.ccy === 'USd' ? 'cents' : def.ccy}`;
};

const monthDay = (ms: number) => {
  const d = new Date(ms);
  return `${MONTHS[d.getUTCMonth()]}. ${d.getUTCDate()}`;
};

function verbFor(pct: number, intraday: boolean): string {
  const a = Math.abs(pct);
  if (pct >= 0) return a > 5 ? 'Soars' : a > 2.5 ? 'Jumps' : a > 1 ? 'Rises' : intraday ? 'Edges Higher' : 'Gains';
  return a > 5 ? 'Plunges' : a > 2.5 ? 'Slides' : a > 1 ? 'Falls' : intraday ? 'Edges Lower' : 'Slips';
}

function moverStory(def: SecurityDef, pct: number, time: number, intraday: boolean): Story {
  const name = shortName(def);
  const q = engine.quote(def.id)!;
  const rs = rangeStats(def.id);
  const yr = periodChange(def.id, '1Y');
  const bench = def.region === 'Americas' ? 'SPX Index' : def.region === 'EMEA' ? 'SXXP Index' : 'NKY Index';
  const benchYr = periodChange(bench, '1Y');
  const c = consensus(def);
  const volRatio = rs.avgVol30 > 0 ? q.volume / rs.avgVol30 : NaN;
  const verb = verbFor(pct, intraday);
  const suffix = intraday
    ? Math.abs(pct) > 3
      ? pct > 0 ? 'to Lead Gainers' : 'to Lead Decliners'
      : 'in Active Trading'
    : Math.abs(pct) > 3
      ? 'Biggest Move in Weeks'
      : pct > 0 ? 'Shares Extend Advance' : 'Shares Retreat';
  const headline = `${name} ${verb} ${fmtNum(Math.abs(pct), 1)}%${intraday ? ' ' : '; '}${suffix}`;
  const body = [
    `${name} shares ${pct >= 0 ? 'rose' : 'fell'} ${fmtNum(Math.abs(pct), 1)}% to ${fmtPx(def, q.last)} in ${CITY[def.country] ?? 'local'} trading${intraday ? '' : ' at the close'}, ${Number.isFinite(volRatio) ? `on volume ${fmtNum(volRatio, 1)} times the 30-day average` : 'in active trading'}.`,
    `The stock has ${yr >= 0 ? 'gained' : 'lost'} ${fmtNum(Math.abs(yr), 1)}% over the past 12 months, compared with a ${fmtSigned(benchYr, 1)}% move in the ${shortName(engine.get(bench)!)}. Its 52-week range is ${fmtNum(rs.lo52, def.dec)} to ${fmtNum(rs.hi52, def.dec)}.`,
    `${c.buy} of ${c.n} analysts tracked by Armin rate the stock a buy, ${c.hold} rate it hold and ${c.sell} sell; the average 12-month price target of ${fmtNum(c.avg, def.dec)} implies ${fmtPct((c.avg / q.last - 1) * 100, 1)} from the latest price.`,
    SIM_NOTE,
  ];
  return {
    id: `mover:${def.id}:${Math.floor(time / 600_000)}`,
    time,
    headline,
    body,
    tickers: [def.id, bench],
    topics: ['STK', SECTOR_TOPIC[def.eq?.sector ?? ''] ?? 'STK', ...(Math.abs(pct) > 4 ? ['TOP'] : [])],
    source: 'ARMN',
    hot: Math.abs(pct) > 5,
  };
}

function regionWrap(region: 'US' | 'EU' | 'ASIA', time: number, final: boolean): Story {
  const ids = region === 'US' ? ['SPX Index', 'INDU Index', 'CCMP Index', 'RTY Index'] : region === 'EU' ? ['SXXP Index', 'SX5E Index', 'DAX Index', 'UKX Index', 'CAC Index'] : ['NKY Index', 'HSI Index', 'SHCOMP Index', 'KOSPI Index', 'AS51 Index'];
  const lead = engine.get(ids[0])!;
  const pct = engine.quote(lead.id)!.pct;
  const others = ids.slice(1).map((id) => {
    const d = engine.get(id)!;
    const q = engine.quote(id)!;
    return `the ${shortName(d)} ${q.pct >= 0 ? 'added' : 'lost'} ${fmtNum(Math.abs(q.pct), 2)}%`;
  });
  const eqs = engine.securities.filter((d) => d.cls === 'equity' && (region === 'US' ? d.country === 'US' : region === 'EU' ? d.region === 'EMEA' : d.region === 'APAC'));
  const sorted = eqs.map((d) => ({ d, p: engine.quote(d.id)!.pct })).sort((a, b) => b.p - a.p);
  const best = sorted.slice(0, 2);
  const worst = sorted.slice(-2).reverse();
  const y10 = engine.quote('USGG10YR Index')!;
  const dxy = engine.quote('DXY Curncy')!;
  const oil = engine.quote('CL1 Comdty')!;
  const label = region === 'US' ? 'US Stocks' : region === 'EU' ? 'European Stocks' : 'Asian Stocks';
  const mood = pct > 0.8 ? 'Rally' : pct > 0.15 ? 'Climb' : pct > -0.15 ? 'Hold Steady' : pct > -0.8 ? 'Slip' : 'Slide';
  const driver =
    Math.abs(y10.chg) > 0.04
      ? `as Treasury Yields ${y10.chg > 0 ? 'Climb' : 'Fall'}`
      : best[0].p > 3
        ? `as ${shortName(best[0].d)} Leads`
        : worst[0].p < -3
          ? `as ${shortName(worst[0].d)} Weighs`
          : oil.pct > 2
            ? 'as Oil Jumps'
            : 'Ahead of Data';
  return {
    id: `wrap:${region}:${Math.floor(time / 1_800_000)}${final ? ':close' : ''}`,
    time,
    headline: `${label} ${mood} ${driver}; ${shortName(lead)} ${fmtSigned(pct, 1)}%`,
    body: [
      `The ${shortName(lead)} ${pct >= 0 ? 'rose' : 'fell'} ${fmtNum(Math.abs(pct), 2)}% to ${fmtNum(engine.quote(lead.id)!.last, 2)}${final ? ' at the close' : ''}, while ${others.join(', ')}.`,
      `Among the biggest gainers, ${best.map((b) => `${shortName(b.d)} (${fmtPct(b.p, 1)})`).join(' and ')} led, while ${worst.map((b) => `${shortName(b.d)} (${fmtPct(b.p, 1)})`).join(' and ')} lagged.`,
      `The 10-year Treasury yield ${y10.chg >= 0 ? 'rose' : 'fell'} ${fmtNum(Math.abs(y10.chg * 100), 1)} basis points to ${fmtNum(y10.last, 3)}%. The dollar index was ${dxy.pct >= 0 ? 'up' : 'down'} ${fmtNum(Math.abs(dxy.pct), 2)}% and WTI crude ${oil.pct >= 0 ? 'gained' : 'lost'} ${fmtNum(Math.abs(oil.pct), 1)}% to $${fmtNum(oil.last, 2)} a barrel.`,
      SIM_NOTE,
    ],
    tickers: [lead.id, ...ids.slice(1), ...best.map((b) => b.d.id), ...worst.map((b) => b.d.id)],
    topics: ['TOP', 'STK'],
    source: 'ARMN',
  };
}

function ecoStory(e: EcoEvent): Story {
  const country = COUNTRY_NAMES[e.country] ?? e.country;
  const unit = e.unit === '%' ? '%' : e.unit ? e.unit : '';
  const v = (x: number | null) => (x == null ? '--' : `${fmtNum(x, e.dec)}${unit}`);
  const diff = e.actual != null && e.survey != null ? e.actual - e.survey : 0;
  const tone = e.kind === 'rate' ? (diff === 0 ? 'Holds' : diff > 0 ? 'Raises' : 'Cuts') : diff > 0 ? 'Beats' : diff < 0 ? 'Misses' : 'Matches';
  const headline =
    e.kind === 'rate'
      ? `*${country.toUpperCase()} ${e.name.toUpperCase()} ${tone === 'Holds' ? 'UNCHANGED AT' : 'SET AT'} ${v(e.actual)}; EST. ${v(e.survey)}`
      : `*${e.country} ${e.name.toUpperCase()} ${v(e.actual)} (${e.period.toUpperCase()}); EST. ${v(e.survey)}`;
  const reaction = e.country === 'US' ? engine.quote('USGG2YR Index') : undefined;
  return {
    id: `eco:${e.id}`,
    time: e.time,
    headline,
    body: [
      `${country}'s ${e.name.toLowerCase().startsWith('change') ? e.name : e.name} came in at ${v(e.actual)} for ${e.period}, ${tone === 'Matches' ? 'in line with' : tone === 'Beats' ? 'above' : tone === 'Misses' ? 'below' : 'versus'} the median estimate of ${v(e.survey)} in a survey of economists. The prior reading was ${v(e.prior)}${e.revised != null ? `, revised to ${v(e.revised)}` : ''}.`,
      reaction ? `Two-year Treasury yields were at ${fmtNum(reaction.last, 3)}% after the release, ${reaction.chg >= 0 ? 'up' : 'down'} ${fmtNum(Math.abs(reaction.chg * 100), 1)} basis points on the day.` : `The release is one of the key data points watched by policy makers in ${country}.`,
      SIM_NOTE,
    ],
    tickers: e.country === 'US' ? ['USGG2YR Index', 'DXY Curncy'] : [],
    topics: ['ECO', ...(e.kind === 'rate' ? ['CB', 'TOP'] : []), ...(e.relevance >= 3 ? ['TOP'] : []), ...(e.country === 'US' ? ['RATES'] : [])],
    source: 'ECO',
    hot: e.relevance >= 3,
  };
}

function earningsStory(def: SecurityDef, ev: ReturnType<typeof earningsHistory>[number]): Story {
  const name = shortName(def);
  const beat = (ev.surprise ?? 0) >= 0;
  const cur = def.ccy === 'USD' ? '$' : '';
  const eps = (x: number) => `${cur}${fmtNum(x, 2)}${cur ? '' : ` ${def.ccy === 'GBp' ? 'GBP' : def.ccy}`}`;
  const rev = (x: number) => `${cur}${fmtNum(x / 1000, 2)} billion`;
  return {
    id: `earn:${def.id}:${ev.period}`,
    time: ev.date + (ev.timing === 'Aft-mkt' ? 20.5 : 11.5) * 3600_000,
    headline: `${name} ${ev.period} ${beat ? 'Profit Tops' : 'Profit Trails'} Estimates; Revenue ${rev(ev.revAct ?? ev.revEst)}`,
    body: [
      `${name} reported ${ev.period} earnings per share of ${eps(ev.actual ?? 0)}, ${beat ? 'beating' : 'missing'} the average analyst estimate of ${eps(ev.estimate)} by ${fmtNum(Math.abs(ev.surprise ?? 0), 1)}%. Revenue was ${rev(ev.revAct ?? 0)} versus estimates of ${rev(ev.revEst)}.`,
      `The results were released ${ev.timing === 'Aft-mkt' ? 'after the market close' : 'before the market open'}. Shares last traded at ${fmtPx(def, engine.quote(def.id)!.last)}.`,
      SIM_NOTE,
    ],
    tickers: [def.id],
    topics: ['EARN', 'STK', SECTOR_TOPIC[def.eq!.sector] ?? 'STK', ...(def.eq!.shares * def.px > 5e5 ? ['TOP'] : [])],
    source: 'ARMN',
  };
}

function analystStory(def: SecurityDef, v: ReturnType<typeof analystViews>[number]): Story {
  const name = shortName(def);
  const verb = v.action === 'Upgrade' ? 'Raised to' : v.action === 'Downgrade' ? 'Cut to' : v.action === 'Initiate' ? 'Started at' : v.action === 'Raise PT' ? 'PT Raised to' : v.action === 'Cut PT' ? 'PT Cut to' : 'Reiterated';
  const target = fmtNum(v.target, def.dec);
  const headline = v.action === 'Raise PT' || v.action === 'Cut PT' ? `${name} ${verb} ${target} at ${v.firm}; ${v.rating}` : `${name} ${verb} ${v.rating} at ${v.firm}; PT ${target}`;
  return {
    id: `anr:${def.id}:${v.firm}:${v.date}`,
    time: v.date + 11 * 3600_000,
    headline,
    body: [
      `${v.firm} ${v.action === 'Maintain' ? 'reiterated its' : 'set a'} ${v.rating.toLowerCase()} rating on ${name} with a 12-month price target of ${target}${v.prevTarget !== v.target ? `, from ${fmtNum(v.prevTarget, def.dec)}` : ''}.`,
      `${consensus(def).buy} of ${consensus(def).n} analysts covering the company recommend buying the stock. See ANR for the full list of recommendations.`,
      SIM_NOTE,
    ],
    tickers: [def.id],
    topics: ['ANALYST', 'STK', SECTOR_TOPIC[def.eq!.sector] ?? 'STK'],
    source: 'ARMN',
  };
}

function assetStory(id: string, time: number): Story | null {
  const def = engine.get(id);
  const q = engine.quote(id);
  if (!def || !q) return null;
  const name = shortName(def);
  if (def.cls === 'commodity') {
    const per = def.cmd!.unit.replace('.', '');
    return {
      id: `cmd:${id}:${Math.floor(time / 3_600_000)}`,
      time,
      headline: `${name.charAt(0).toUpperCase() + name.slice(1)} ${verbFor(q.pct, true)} ${fmtNum(Math.abs(q.pct), 1)}% to ${fmtNum(q.last, def.dec)}`,
      body: [
        `${name.charAt(0).toUpperCase() + name.slice(1)} futures ${q.pct >= 0 ? 'rose' : 'fell'} ${fmtNum(Math.abs(q.pct), 2)}% to ${fmtNum(q.last, def.dec)} ${per} on ${def.cmd!.exch}, after trading between ${fmtNum(q.low, def.dec)} and ${fmtNum(q.high, def.dec)} in the session.`,
        `Prices are ${periodChange(id, 'YTD') >= 0 ? 'up' : 'down'} ${fmtNum(Math.abs(periodChange(id, 'YTD')), 1)}% this year. The dollar index ${engine.quote('DXY Curncy')!.pct >= 0 ? 'rose' : 'fell'} ${fmtNum(Math.abs(engine.quote('DXY Curncy')!.pct), 2)}%.`,
        SIM_NOTE,
      ],
      tickers: [id, 'DXY Curncy'],
      topics: ['CMDTY', ...(def.cmd!.group === 'Energy' ? ['ENERGY'] : def.cmd!.group.includes('Metal') ? ['METALS'] : ['AGS'])],
      source: 'ARMN',
    };
  }
  if (def.cls === 'crypto') {
    return {
      id: `cry:${id}:${Math.floor(time / 3_600_000)}`,
      time,
      headline: `${name} ${verbFor(q.pct, true)} ${fmtNum(Math.abs(q.pct), 1)}% to $${fmtNum(q.last, q.last > 100 ? 0 : 2)}`,
      body: [
        `${name} ${q.pct >= 0 ? 'climbed' : 'dropped'} ${fmtNum(Math.abs(q.pct), 2)}% to $${fmtNum(q.last, 2)}, trading in a range of $${fmtNum(q.low, 2)} to $${fmtNum(q.high, 2)}.`,
        `The token has ${periodChange(id, '1M') >= 0 ? 'gained' : 'lost'} ${fmtNum(Math.abs(periodChange(id, '1M')), 1)}% over the past month. Crypto-linked equities such as Coinbase moved ${fmtPct(engine.quote('COIN US Equity')!.pct, 1)}.`,
        SIM_NOTE,
      ],
      tickers: [id, 'COIN US Equity'],
      topics: ['CRYPTO'],
      source: 'ARMN',
    };
  }
  if (def.cls === 'fx') {
    return {
      id: `fx:${id}:${Math.floor(time / 3_600_000)}`,
      time,
      headline: `${def.fx ? `${def.fx.base}/${def.fx.quote}` : def.ticker} ${q.pct >= 0 ? 'Rises' : 'Falls'} ${fmtNum(Math.abs(q.pct), 2)}% to ${fmtNum(q.last, def.dec)}`,
      body: [
        `The ${def.name.toLowerCase()} traded at ${fmtNum(q.last, def.dec)}, ${q.pct >= 0 ? 'up' : 'down'} ${fmtNum(Math.abs(q.pct), 2)}% on the day, after a range of ${fmtNum(q.low, def.dec)}-${fmtNum(q.high, def.dec)}.`,
        `The Armin dollar gauge is ${engine.quote('DXY Curncy')!.pct >= 0 ? 'higher' : 'lower'} by ${fmtNum(Math.abs(engine.quote('DXY Curncy')!.pct), 2)}%, while US two-year yields moved ${fmtNum(engine.quote('USGG2YR Index')!.chg * 100, 1)} basis points.`,
        SIM_NOTE,
      ],
      tickers: [id, 'DXY Curncy'],
      topics: ['FX'],
      source: 'ARMN',
    };
  }
  if (def.cls === 'rate') {
    const bp = q.chg * 100;
    return {
      id: `rates:${id}:${Math.floor(time / 3_600_000)}`,
      time,
      headline: `${def.curve === 'US' ? 'Treasury' : (COUNTRY_NAMES[def.country] ?? def.country)} ${def.tenor}-Year Yield ${bp >= 0 ? 'Rises' : 'Falls'} ${fmtNum(Math.abs(bp), 1)} Basis Points to ${fmtNum(q.last, 3)}%`,
      body: [
        `The ${def.tenor}-year ${def.curve === 'US' ? 'Treasury' : 'government bond'} yield moved ${fmtSigned(bp, 1)} basis points to ${fmtNum(q.last, 3)}%. The yield has ${q.last >= rangeStats(id).hi52 - 0.05 ? 'touched its highest in a year' : `ranged between ${fmtNum(rangeStats(id).lo52, 3)}% and ${fmtNum(rangeStats(id).hi52, 3)}% over the past 52 weeks`}.`,
        `Traders are watching upcoming central bank meetings; see WIRP for market-implied rate probabilities.`,
        SIM_NOTE,
      ],
      tickers: [id],
      topics: ['RATES', ...(Math.abs(bp) > 6 ? ['TOP'] : [])],
      source: 'ARMN',
    };
  }
  return null;
}

