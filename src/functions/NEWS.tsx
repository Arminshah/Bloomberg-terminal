function StoryView({ story, onBack }: { story: Story; onBack: () => void }) {
  return (
    <article className="story">
      <button type="button" className="btn show-m" onClick={onBack}>
        ‹ Headlines
      </button>
      <div className="meta">
        <span className="amber">{story.source}</span>
        <span>
          {fmtDate(story.time)} {fmtTime(story.time)}
        </span>
        {story.real ? <span className="badge live">REAL NEWS</span> : <span className="badge sim">SIMULATED</span>}
      </div>
      <h2>{story.headline.replace(/^\*/, '')}</h2>
      {story.tickers.length > 0 && (
        <div className="tickers">
          {story.tickers
            .filter((t, i, a) => a.indexOf(t) === i && engine.get(t))
            .slice(0, 10)
            .map((t) => (
              <SecLink key={t} id={t}>
                {t}
              </SecLink>
            ))}
        </div>
      )}
      {story.body.map((p, i) => (
        <p key={i} className={p.startsWith('Generated by') ? 'sim' : ''}>
          {p}
        </p>
      ))}
      {story.url && (
        <p>
          <a href={story.url} target="_blank" rel="noreferrer noopener" className="blue">
            Read the full story at {story.source} ↗
          </a>
        </p>
      )}
    </article>
  );
}

function NewsScreen({ code, title, ticker, initialTopic, query }: { code: string; title: string; ticker?: string; initialTopic?: string; query?: string }) {
  const panel = usePanelId();
  const stories = news.use((n) => n.stories);
  const realFeed = feedStatus.use((f) => f.news);
  const [topic, setTopic] = useState(initialTopic ?? 'ALL');
  const [q, setQ] = useState(query ?? '');
  const [sel, setSel] = useState<string | null>(null);
  const tabs = [{ n: 1, label: 'All' }, ...NEWS_TOPICS.map((t, i) => ({ n: i + 2, label: t.label }))];
  const topicCode = (n: number) => (n === 1 ? 'ALL' : NEWS_TOPICS[n - 2].code);
  const tabN = topic === 'ALL' ? 1 : NEWS_TOPICS.findIndex((t) => t.code === topic) + 2;
  const list = useMemo(() => stories.filter((s) => storyMatches(s, ticker ? undefined : topic, ticker, q.trim() || undefined)).slice(0, 300), [stories, topic, ticker, q]);
  const current = list.find((s) => s.id === sel) ?? (sel ? stories.find((s) => s.id === sel) : undefined) ?? list[0];
  return (
    <div className="fn-fill">
      <FnHeader
        code={code}
        title={title}
        sec={ticker ? engine.get(ticker) : undefined}
        sub={
          <>
            {list.length} stories ·{' '}
            {list.every((x) => x.real) && list.length ? (
              <>
                <RealBadge /> headlines from {desktopData() ? 'Yahoo Finance and its publishers' : 'the connected feed'}
              </>
            ) : list.some((x) => x.real) ? (
              <>
                <RealBadge /> blue headlines are real · <SimBadge /> the rest are generated
              </>
            ) : (
              <>
                <SimBadge /> generated headlines{realFeed === 'live' ? '' : '; real headlines need the desktop app or a news key in PDFU'}
              </>
            )}
          </>
        }
        tabs={ticker ? undefined : tabs}
        tab={tabN}
        onTab={(n) => {
          setTopic(topicCode(n));
          setSel(null);
        }}
      />
      <div className="chart-tools">
        <label className="fld" htmlFor={`news-q-${panel}`}>
          Search
        </label>
        <input id={`news-q-${panel}`} className="inp" style={{ width: 220 }} value={q} placeholder="keyword, ticker…" onChange={(e) => setQ(e.target.value)} />
        <span className="muted hide-m">Red = flash headline · Blue = real headline</span>
      </div>
      <div className={`news${sel ? ' reading' : ''}`} style={{ flex: 1, minHeight: 0 }}>
        <div className="news-list" role="list">
          {list.length === 0 && <div className="empty">No stories match.</div>}
          {list.map((s) => (
            <div
              key={s.id}
              role="listitem"
              className={`news-item${s.hot ? ' hot' : ''}${s.real ? ' real' : ''}${current?.id === s.id ? ' sel' : ''}`}
              onClick={() => setSel(s.id)}
            >
              <span className="time">{fmtStamp(s.time, engine.now())}</span>
              <span className="hl">{s.headline}</span>
              <span className="src">{s.source}</span>
            </div>
          ))}
        </div>
        {current ? <StoryView story={current} onBack={() => setSel(null)} /> : <div className="empty">Select a headline.</div>}
      </div>
    </div>
  );
}

export function TOP({ route }: FnProps) {
  const arg = route.args?.toUpperCase();
  const topic = arg && NEWS_TOPICS.some((t) => t.code === arg) ? arg : 'TOP';
  return <NewsScreen code="TOP" title="Top News" initialTopic={topic} />;
}

export function N({ route, sec }: FnProps) {
  const arg = route.args?.toUpperCase();
  const topic = arg && NEWS_TOPICS.some((t) => t.code === arg) ? arg : undefined;
  if (sec) return <NewsScreen code="N" title="News" ticker={sec.id} />;
  return <NewsScreen code="N" title="News Search" initialTopic={topic} query={topic ? undefined : arg} />;
}

export function CN({ sec }: FnProps) {
  useEffect(() => requestCompanyNews(sec!.id), [sec]);
  return <NewsScreen code="CN" title="Company News" ticker={sec!.id} />;
}

/** Simulated readership: bigger, hotter and market-wide stories draw more readers, accumulating after release. */
function reads(s: Story, now: number): number {
  let h = 0;
  for (let i = 0; i < s.id.length; i++) h = (h * 31 + s.id.charCodeAt(i)) >>> 0;
  let weight = 1 + (h % 1000) / 400;
  if (s.hot) weight *= 3;
  if (s.topics.includes('TOP')) weight *= 2;
  if (s.topics.includes('CB') || s.topics.includes('ECO')) weight *= 1.5;
  if (s.real) weight *= 1.4;
  weight *= 1 + Math.min(4, s.tickers.length) * 0.15;
  const ageMin = Math.max(0, (now - s.time) / 60_000);
  return Math.round(900 * weight * (1 - Math.exp(-ageMin / 90)));
}

/** READ: most-read stories. */
export function READ(_: FnProps) {
  const stories = news.use((n) => n.stories);
  const [tab, setTab] = useState(1);
  const [sel, setSel] = useState<string | null>(null);
  const now = engine.now();
  const window = tab === 1 ? 24 * 3600_000 : 7 * 24 * 3600_000;
  const ranked = useMemo(
    () =>
      stories
        .filter((s) => now - s.time <= window && s.time <= now)
        .map((s) => ({ s, r: reads(s, now) }))
        .sort((a, b) => b.r - a.r)
        .slice(0, 40),
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [stories, tab, Math.floor(now / 60_000)],
  );
  const current = ranked.find((x) => x.s.id === sel)?.s ?? ranked[0]?.s;
  return (
    <div className="fn-fill">
      <FnHeader
        code="READ"
        title="Most Read News"
        sub={
          <>
            <SimBadge /> readership ranking (the stories themselves are as listed in N)
          </>
        }
        tabs={[
          { n: 1, label: 'Last 24 hours' },
          { n: 2, label: 'Last 7 days' },
        ]}
        tab={tab}
        onTab={setTab}
      />
      <div className={`news${sel ? ' reading' : ''}`} style={{ flex: 1, minHeight: 0 }}>
        <div className="news-list" role="list">
          {ranked.length === 0 && <div className="empty">No stories yet.</div>}
          {ranked.map(({ s, r }, i) => (
            <div key={s.id} role="listitem" className={`news-item${s.hot ? ' hot' : ''}${current?.id === s.id ? ' sel' : ''}`} onClick={() => setSel(s.id)}>
              <span className="time yellow">{i + 1})</span>
              <span className="hl">{s.headline}</span>
              <span className="src">{r.toLocaleString('en-US')}</span>
            </div>
          ))}
        </div>
        {current ? <StoryView story={current} onBack={() => setSel(null)} /> : <div className="empty">Select a headline.</div>}
      </div>
    </div>
  );
}
